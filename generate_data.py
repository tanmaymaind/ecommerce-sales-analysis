"""
generate_data.py — creates data/raw_sales.csv

IMPORTANT: this is a SYNTHETIC dataset, generated by this script with a fixed
random seed (42) so anyone can reproduce it exactly. It is NOT real sales
data and is NOT downloaded from Kaggle or anywhere else. It was modelled to
look like a realistic Indian e-commerce order export — Indian cities and
regions, common product categories, INR price ranges, a festive-season
(Oct-Nov) spike — and a small amount of messiness was added on purpose
(duplicate rows, missing values, inconsistent spellings/casing) so the
cleaning step has real work to do.

Run:  python3 generate_data.py
Out:  data/raw_sales.csv
"""

import csv
import random
from datetime import date, timedelta

random.seed(42)

# ---------------------------------------------------------------- catalogue
# city -> region (standard Indian e-commerce zoning)
CITY_REGION = {
    "Delhi": "North", "Jaipur": "North", "Lucknow": "North", "Chandigarh": "North",
    "Bengaluru": "South", "Chennai": "South", "Hyderabad": "South", "Kochi": "South",
    "Mumbai": "West", "Pune": "West", "Ahmedabad": "West", "Surat": "West",
    "Kolkata": "East", "Patna": "East", "Bhubaneswar": "East", "Guwahati": "East",
    "Indore": "Central", "Bhopal": "Central", "Nagpur": "Central", "Raipur": "Central",
}
CITIES = list(CITY_REGION)
# bigger metros get more orders
CITY_WEIGHTS = [10, 4, 4, 3, 11, 7, 8, 3, 12, 7, 6, 3, 8, 3, 3, 2, 4, 3, 5, 2]

# category -> [(product, base price in INR, popularity weight)]
CATALOG = {
    "Electronics": [
        ("Wireless Earbuds", 1499, 10), ("Smartphone", 14999, 7),
        ("Laptop", 52990, 3), ("Smart Watch", 2999, 6),
        ("Bluetooth Speaker", 1999, 6), ("Power Bank", 999, 8),
    ],
    "Fashion": [
        ("Men's T-Shirt", 599, 9), ("Women's Kurti", 1199, 8),
        ("Running Shoes", 2499, 7), ("Denim Jeans", 1799, 7),
        ("Handbag", 1499, 5),
    ],
    "Home & Kitchen": [
        ("Pressure Cooker", 1327, 6), ("Mixer Grinder", 3499, 5),
        ("Bedsheet Set", 1099, 6), ("Air Fryer", 5999, 4),
        ("Dinner Set", 2199, 5),
    ],
    "Beauty": [
        ("Face Serum", 699, 7), ("Lipstick", 399, 6),
        ("Shampoo", 349, 8), ("Perfume", 1299, 5),
    ],
    "Sports": [
        ("Yoga Mat", 799, 6), ("Dumbbell Set", 1899, 4), ("Cricket Bat", 2999, 4),
    ],
    "Books": [
        ("Novel", 299, 6), ("Exam Guide", 499, 6), ("Notebook Pack", 249, 5),
    ],
}
CATEGORIES = list(CATALOG)
CATEGORY_WEIGHTS = [30, 25, 18, 10, 8, 9]

N_CUSTOMERS = 2500
N_ORDERS = 12000

# monthly order volume weights — growth through the year + Oct/Nov festive spike
MONTH_WEIGHTS = [7, 7, 8, 8, 8, 9, 9, 10, 10, 14, 13, 11]

STATUSES = ["Delivered", "Cancelled", "Returned"]
STATUS_WEIGHTS = [86, 9, 5]


def pick(weighted_items, weights):
    return random.choices(weighted_items, weights=weights, k=1)[0]


def main():
    # customer pool with uneven activity — a minority orders again and again
    customers = [f"CUST{i:04d}" for i in range(1, N_CUSTOMERS + 1)]
    cust_weights = [random.choice([1, 1, 1, 2, 2, 3, 5, 8]) for _ in customers]

    start = date(2025, 1, 1)
    rows = []
    for i in range(1, N_ORDERS + 1):
        month = pick(list(range(1, 13)), MONTH_WEIGHTS)
        day = random.randint(1, 28)
        order_date = date(2025, month, day)
        customer = random.choices(customers, weights=cust_weights, k=1)[0]
        category = pick(CATEGORIES, CATEGORY_WEIGHTS)
        product, base_price, _ = random.choices(
            CATALOG[category], weights=[w for _, _, w in CATALOG[category]], k=1
        )[0]
        price = round(base_price * random.uniform(0.9, 1.1))
        qty = random.choices([1, 2, 3, 4], weights=[78, 15, 5, 2], k=1)[0]
        city = pick(CITIES, CITY_WEIGHTS)
        status = pick(STATUSES, STATUS_WEIGHTS)
        rows.append({
            "order_id": f"ORD{i:05d}",
            "order_date": order_date.isoformat(),
            "customer_id": customer,
            "city": city,
            "region": CITY_REGION[city],
            "category": category,
            "product": product,
            "quantity": qty,
            "unit_price": price,
            "status": status,
        })

    rows.sort(key=lambda r: (r["order_date"], r["order_id"]))

    # ------------------------------------------------ deliberate messiness
    # inconsistent spellings / casing on ~2% of rows
    city_variants = {"Bengaluru": ["Bangalore", "bengaluru", "Bengaluru "],
                     "Mumbai": ["Bombay", "mumbai", "Mumbai "],
                     "Delhi": ["delhi", "New Delhi", "Delhi "],
                     "Kolkata": ["Calcutta", "kolkata"]}
    for r in rows:
        if random.random() < 0.02 and r["city"] in city_variants:
            r["city"] = random.choice(city_variants[r["city"]])
        if random.random() < 0.015:
            r["category"] = random.choice([r["category"].lower(), r["category"].upper()])
        if random.random() < 0.015:
            r["status"] = random.choice([r["status"].lower(), r["status"].upper(),
                                         r["status"] + " "])

    # missing values: city ~1%, quantity ~0.5%, unit_price ~0.5%
    for r in rows:
        x = random.random()
        if x < 0.010:
            r["city"] = ""
            r["region"] = ""
        elif x < 0.015:
            r["quantity"] = ""
        elif x < 0.020:
            r["unit_price"] = ""

    # invalid values: a few zero quantities
    for r in random.sample(rows, 30):
        r["quantity"] = 0

    # exact duplicate rows (~1%)
    dupes = [dict(r) for r in random.sample(rows, 120)]
    rows.extend(dupes)
    random.shuffle(rows)

    fields = ["order_id", "order_date", "customer_id", "city", "region",
              "category", "product", "quantity", "unit_price", "status"]
    with open("data/raw_sales.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)

    print(f"Wrote data/raw_sales.csv with {len(rows)} rows "
          f"(includes ~120 deliberate duplicates and other messiness)")


if __name__ == "__main__":
    main()
