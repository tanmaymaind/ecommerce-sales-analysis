"""Streamlit dashboard for the E-Commerce Sales Analysis project.

Loads the committed cleaned dataset (data/cleaned_sales.csv) and shows the
headline numbers and charts from the analysis. Revenue counts Delivered
orders only — the same rule used in queries.sql and python_analysis.py.

Run locally:  streamlit run app.py
"""

from pathlib import Path

import pandas as pd
import streamlit as st

DATA_PATH = Path(__file__).parent / "data" / "cleaned_sales.csv"


def format_inr(value: float) -> str:
    """Format a number as rupees with Indian digit grouping (₹4,70,89,730)."""
    n = int(round(value))
    sign = "-" if n < 0 else ""
    s = str(abs(n))
    if len(s) <= 3:
        return f"₹{sign}{s}"
    head, tail = s[:-3], s[-3:]
    parts = []
    while len(head) > 2:
        parts.insert(0, head[-2:])
        head = head[:-2]
    if head:
        parts.insert(0, head)
    return "₹" + sign + ",".join(parts + [tail])


@st.cache_data
def load_data() -> pd.DataFrame:
    df = pd.read_csv(DATA_PATH, parse_dates=["order_date"])
    df["revenue_calc"] = df["quantity"] * df["unit_price"]
    return df


def main() -> None:
    st.set_page_config(page_title="E-Commerce Sales Analysis", layout="wide")
    st.title("E-Commerce Sales Analysis")
    st.write(
        "A year of Indian e-commerce orders (synthetic dataset, 2025) — "
        "cleaned in Python and analysed in both SQL and pandas. "
        "Revenue counts Delivered orders only."
    )

    df = load_data()
    delivered = df[df["status"] == "Delivered"]

    # ---- KPI row -------------------------------------------------------
    total_revenue = delivered["revenue_calc"].sum()
    total_orders = len(delivered)
    avg_order_value = total_revenue / total_orders if total_orders else 0.0
    lost_orders = df[df["status"].isin(["Cancelled", "Returned"])]
    cancel_return_pct = 100.0 * len(lost_orders) / len(df) if len(df) else 0.0

    col1, col2, col3, col4 = st.columns(4)
    col1.metric("Total Revenue (Delivered)", format_inr(total_revenue))
    col2.metric("Total Orders (Delivered)", f"{total_orders:,}")
    col3.metric("Average Order Value", format_inr(avg_order_value))
    col4.metric("Cancellation + Return", f"{cancel_return_pct:.2f}%")

    # ---- Charts --------------------------------------------------------
    st.subheader("Revenue by category")
    by_category = (
        delivered.groupby("category")["revenue_calc"]
        .sum()
        .sort_values(ascending=False)
        .rename("Revenue (₹)")
    )
    st.bar_chart(by_category)

    st.subheader("Revenue by region")
    by_region = (
        delivered.groupby("region")["revenue_calc"]
        .sum()
        .sort_values(ascending=False)
        .rename("Revenue (₹)")
    )
    st.bar_chart(by_region)

    st.subheader("Monthly revenue trend")
    monthly = (
        delivered.groupby("month")["revenue_calc"].sum().rename("Revenue (₹)")
    )
    st.line_chart(monthly)

    # ---- Tables --------------------------------------------------------
    st.subheader("Top 10 products by revenue")
    top_products = (
        delivered.groupby("product")
        .agg(Orders=("order_id", "count"), Revenue=("revenue_calc", "sum"))
        .sort_values("Revenue", ascending=False)
        .head(10)
    )
    top_products["Revenue"] = top_products["Revenue"].map(format_inr)
    st.dataframe(top_products, use_container_width=True)

    st.subheader("Data preview")
    st.dataframe(df.head(10), use_container_width=True)

    # ---- Key findings (from README.md) ---------------------------------
    st.subheader("Key findings")
    st.markdown(
        """
1. **Electronics is the business.** It brings ₹3.31 crore of the ₹4.71
   crore delivered revenue (70.29%), and the Laptop alone is ₹1.77 crore —
   37.6% of all revenue from a single product.
2. **₹69.5 lakh of orders never became revenue.** 1,596 of 11,729 orders
   (13.61%) were cancelled or returned, worth ₹69,49,561 — about 12.9% of
   the value of everything that was ordered.
3. **Buyers come back.** 79.78% of customers placed two or more delivered
   orders, and the top 10 customers alone account for ₹24,08,466 (5.11% of
   revenue) — repeat buyers, not one-time traffic, drive this store.
"""
    )
    st.caption(
        "Dataset: synthetic, generated by generate_data.py (seed 42) and "
        "cleaned by cleaning.py — see README.md for the full analysis, the "
        "10 SQL + Python business questions, and the Power BI pack."
    )


if __name__ == "__main__":
    main()
